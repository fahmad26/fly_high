// Build deterministic Roblox/localization exports from reviewed source/English pairs.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const rows = JSON.parse(fs.readFileSync(path.join(root, 'assets/localization/id-en.json'), 'utf8'));
const seen = new Set();
const escapePattern = s => s.replace(/[\^$().%[\]*+?\-]/g, '%$&');
const spec = /%((?:0?\d+)?(?:\.\d+)?[dfs%])/g;
const entries = rows.map(({source, en}, i) => {
  if (typeof source !== 'string' || typeof en !== 'string' || seen.has(source)) throw Error('Invalid/duplicate source: '+source);
  seen.add(source);
  let count=0, cursor=0, pattern='^';
  for (const match of source.matchAll(spec)) {
    pattern += escapePattern(source.slice(cursor, match.index));
    if (match[1] === '%') pattern += '%%';
    else { count++; pattern += match[1].endsWith('s') ? '(.-)' : '([%d%.,%+%-]+)'; }
    cursor = match.index + match[0].length;
  }
  pattern += escapePattern(source.slice(cursor))+'$';
  let targetCount=0;
  const template=en.replace(spec, (_, s)=>s==='%'?'%':`{${++targetCount}}`);
  if (count !== targetCount) throw Error('Parameter mismatch: '+source);
  const rawCaptures=['MASTER • %s','KRU • %s','ARWAH • %s'].includes(source);
  return {key:'flyhigh_'+String(i+1).padStart(4,'0'),source,en,...(count?{pattern,template,rawCaptures}:{} )};
});
const output=path.join(root,'audit/sources/ReplicatedStorage/FlyHigh/Modules/LocalizationCatalog.luau');
fs.writeFileSync(output, '--!strict\n-- Generated by tools/build-localization.cjs; edit assets/localization/id-en.json.\nreturn game:GetService("HttpService"):JSONDecode([==[\n'+JSON.stringify(entries)+'\n]==])\n');
const quote=s=>'"'+s.replaceAll('"','""')+'"';
const cloudTemplate=s=>{ let i=0; return s.replace(spec,(_,type)=>type==='%'?'%':`{arg${++i}}`); };
// Cloud CSV uses supported language code "en"; runtime tables use the en-us locale.
fs.writeFileSync(path.join(root,'assets/localization/id-en.csv'),'Key,Source,Context,Example,en\r\n'+entries.map(e=>[e.key,cloudTemplate(e.source),'','',cloudTemplate(e.en)].map(quote).join(',')).join('\r\n')+'\r\n');
console.log(JSON.stringify({entries:entries.length,dynamicTemplates:entries.filter(e=>e.pattern).length,output}));
